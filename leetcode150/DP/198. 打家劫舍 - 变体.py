"""
你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。并且首尾不能一起偷
给定一个代表每个房屋存放金额的非负整数数组，计算你 不触动警报装置的情况下 ，一夜之内能够偷窃到的最高金额。

（在 198 的基础上新增约束：房屋首尾相连围成一圈，第 0 间和最后一间视为相邻，不能同时偷。
  核心做法：把"环形"拆成两个"直线"子问题 —— 不偷第一间 / 不偷最后一间，取两者最大值）

示例 1：
输入：[1,2,3,1]
输出：4
解释：偷 0 号房 (1) + 2 号房 (3) = 4，首尾没有同时偷，合法。

示例 2：
输入：[2,7,9,3,1]
输出：11
解释：198 里的最优解 2 + 9 + 1 = 12 同时偷了首尾，本变体非法；
     退而求其次偷 0 号房 (2) + 2 号房 (9) = 11。

示例 3：
输入：[1,3,1,3,100]
输出：103
解释：不偷第一间时，[3,1,3,100] 最优为 3 + 100 = 103。

提示：
1 <= nums.length <= 100
0 <= nums[i] <= 400
"""
from typing import List
class Solution:
    def rob(self,  nums: List[int]) -> int:
        def rob_range(ns: List[int]) -> int:
            """直线版打家劫舍（就是 198）：dp[i] 表示只考虑前 i 间房能偷到的最大金额"""
            if not ns:
                return 0
            dp = [0] * (len(ns) + 1)
            for i in range(1, len(ns) + 1):
                # 偷第 i 间（下标 i-1）：dp[i-2] + ns[i-1]  |  不偷第 i 间：dp[i-1]
                dp[i] = max(dp[i - 2] + ns[i - 1], dp[i - 1])
            return dp[-1]

        if len(nums) == 1:  # 只有一间房，不存在首尾冲突
            return nums[0]
        # 首尾不能同时偷：
        #   情况一 nums[:-1] 不偷最后一间  情况二 nums[1:] 不偷第一间
        #   任意合法方案必然属于其中之一，取最大即可
        return max(rob_range(nums[:-1]), rob_range(nums[1:]))


if __name__ == '__main__':
    s = Solution()
    print(s.rob([1, 2, 3, 1]))      # 输出: 4
    print(s.rob([2, 7, 9, 3, 1]))   # 输出: 11
    print(s.rob([1]))               # 输出: 1
    print(s.rob([1, 3, 1, 3, 100])) # 输出: 103
